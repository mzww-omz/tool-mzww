import assert from 'node:assert/strict';

// Dependency-free test body: pass a Playwright Page from your existing runner.
export default async function smoke(page, origin = 'http://127.0.0.1:5174') {
 const errors = [];
 const listener = error => errors.push(error.message);
 page.on('pageerror', listener);
 const consoleListener = message => { if (['error','warning'].includes(message.type())) errors.push(message.text()); };
 page.on('console', consoleListener);
 await page.setViewportSize({ width:1440, height:1000 });
 await page.goto(origin);
 await page.evaluate(() => localStorage.clear());
 await page.reload();
 const output = () => page.getByRole('textbox', { name:'出力', exact:true });
 const open = async id => {
  await page.locator(`nav a[href="/tools/${id}"]`).click();
  await page.waitForURL(`${origin}/tools/${id}`);
  await page.locator(`nav a[href="/tools/${id}"][aria-current="page"]`).waitFor();
  await page.locator('.tool-body textarea, .tool-body input, .life-grid').first().waitFor();
 };
 const button = name => page.getByRole('button', { name, exact:true });
 await page.context().grantPermissions(['clipboard-read','clipboard-write']);
 await page.locator('#counter-text').fill('A猫\nB');
 assert.equal(await page.locator('.stats-strip strong').first().innerText(), '4');
 await button('結果をコピー').click();
 assert.match(await page.evaluate(()=>navigator.clipboard.readText()), /文字数: 4/);
 await button('お気に入りに追加').click();
 await open('json');
 await page.locator('#transform-input').fill('{"a":1}');
 await button('整形 · 2スペース').click();
 assert.equal(await output().inputValue(), '{\n  "a": 1\n}');
 await page.locator('#transform-input').fill('{broken}');
 await button('整形 · 2スペース').click();
 await page.getByRole('alert').waitFor();
 await open('counter');
 assert.equal(await page.locator('#counter-text').inputValue(), 'A猫\nB');
 await open('diff');
 await page.getByRole('textbox', { name:'変更前 / BEFORE' }).fill('a\nb');
 await page.getByRole('textbox', { name:'変更後 / AFTER' }).fill('a\nc');
 await button('差分を比較 ↗').click();
 assert.equal(await page.locator('.diff-remove pre').innerText(), 'b');
 assert.equal(await page.locator('.diff-add pre').innerText(), 'c');
 await open('replace');
 await page.locator('#replace-text').fill('aa bb aa');
 await page.getByRole('textbox', { name:'検索する文字列' }).fill('aa');
 await page.getByRole('textbox', { name:'置換後の文字列' }).fill('猫');
 await button('すべて置換 ↗').click();
 assert.equal(await output().inputValue(), '猫 bb 猫');
 await open('base64');
 await page.locator('#transform-input').fill('猫');
 await button('エンコード').click();
 assert.equal(await output().inputValue(), '54yr');
 await page.locator('#transform-input').fill('54yr');
 await button('デコード').click();
 assert.equal(await output().inputValue(), '猫');
 await open('url');
 await page.locator('#transform-input').fill('a b');
 await button('エンコード').click();
 assert.equal(await output().inputValue(), 'a%20b');
 await open('uuid');
 await page.getByRole('spinbutton').fill('3');
 await button('UUID v4を生成 ↗').click();
 assert.equal((await output().inputValue()).split('\n').length, 3);
 await open('hash');
 await page.locator('#hash-text').fill('abc');
 await button('ハッシュを計算 ↗').click();
 await page.waitForFunction(() => document.querySelector('.result-text')?.value.startsWith('ba7816bf'));
 assert.equal(await output().inputValue(), 'ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
 await open('timestamp');
 await page.getByRole('textbox', { name:'値', exact:true }).fill('0');
 await button('変換 ↗').click();
 assert.match(await output().inputValue(), /1970-01-01T00:00:00.000Z/);
 await open('radix');
 await page.getByRole('textbox', { name:'変換する整数' }).fill('255');
 await button('変換 ↗').click();
 assert.equal(await output().inputValue(), '11111111');
 await open('units');
 await button('変換 ↗').click();
 assert.equal(await output().inputValue(), '0.001 km');
 await open('color');
 await page.getByRole('textbox', { name:'カラーコード' }).fill('#00ff00');
 await button('変換 ↗').click();
 assert.match(await output().inputValue(), /rgb\(0, 255, 0\)/);
 await open('random');
 await page.getByRole('spinbutton', { name:'最小値（含む）' }).fill('7');
 await page.getByRole('spinbutton', { name:'最大値（含む）' }).fill('7');
 await page.getByRole('spinbutton', { name:'生成数' }).fill('2');
 await button('乱数を生成 ↗').click();
 assert.equal(await output().inputValue(), '7\n7');
 await open('life');
 await button('1世代進める').click();
 assert.equal(await page.locator('.life-toolbar strong').first().innerText(), '0001');
 const cell = page.locator('[data-cell="0"]');
 await cell.focus();
 await page.keyboard.press('ArrowRight');
 assert.equal(await page.locator(':focus').getAttribute('data-cell'), '1');
 await page.keyboard.press('Space');
 assert.equal(await page.locator('[data-cell="1"]').getAttribute('aria-selected'), 'true');
 await button('再生 ▷').click();
 await page.waitForFunction(() => Number(document.querySelector('.life-toolbar strong')?.textContent) > 1);
 await button('一時停止 Ⅱ').click();
 await open('image');
 const png = await page.evaluate(() => { const c=document.createElement('canvas');c.width=100;c.height=50;c.getContext('2d').fillRect(0,0,100,50);return c.toDataURL('image/png').split(',')[1]; });
 await page.locator('input[type=file]').setInputFiles({name:'test.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
 await page.getByRole('spinbutton', { name:'幅 / px' }).fill('50');
 assert.equal(await page.getByRole('spinbutton', { name:'高さ / px' }).inputValue(), '25');
 await page.getByRole('combobox', { name:'保存形式' }).selectOption('image/webp');
 await button('リサイズ・変換 ↗').click();
 await page.getByRole('link', { name:'画像をダウンロード ↓' }).waitFor();
 const image = await page.evaluate(async () => {const img=document.querySelector('.image-preview img');await img.decode();return {width:img.naturalWidth,height:img.naturalHeight};});
 assert.deepEqual(image, {width:50,height:25});
 const download = page.waitForEvent('download');
 await page.getByRole('link', { name:'画像をダウンロード ↓' }).click();
 assert.equal((await download).suggestedFilename(), 'toolbox-image.webp');
 await page.reload();
 const recent = await page.evaluate(()=>JSON.parse(localStorage.getItem('toolbox:recent')));
 assert.equal(recent[0], 'image');
 assert.ok(recent.includes('life'));
 await button('お気に入り 1').click();
 assert.equal(await page.locator('nav a').count(), 1);
 await page.locator('nav a').first().click();
 assert.equal(await page.locator('#counter-text').inputValue(), '');
 await button('すべて 15').click();
 await page.getByRole('textbox', { name:'ツールを検索' }).fill('ベース64');
 assert.equal(await page.locator('nav a').count(), 1);
 assert.equal(await page.locator('nav a').getAttribute('href'), '/tools/base64');
 await page.getByRole('textbox', { name:'ツールを検索' }).fill('');
 await page.keyboard.press('Control+k');
 assert.equal(await page.locator(':focus').getAttribute('aria-label'), 'ツールを検索');
 await page.setViewportSize({width:390,height:844});
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('aside').isVisible(), false);
 await page.getByRole('button', {name:/ツール一覧/}).click();
 assert.equal(await page.locator('aside').isVisible(), true);
 await page.locator('nav a[href="/tools/json"]').click();
 await page.locator('aside').waitFor({state:'hidden'});
 assert.equal(await page.locator('aside').isVisible(), false);
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
 await page.setViewportSize({width:320,height:740});
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
 await page.getByRole('button', {name:'使い方・キーボードショートカット'}).click();
 assert.equal(await page.getByRole('dialog').isVisible(), true);
 await page.keyboard.press('Escape');
 assert.equal(await page.getByRole('dialog').isVisible(), false);
 await page.goto(`${origin}/tools/not-a-tool`);
 await page.getByRole('heading', {name:'ツールが見つかりません'}).waitFor();
 page.off('pageerror', listener);
 page.off('console', consoleListener);
 assert.deepEqual(errors, []);
 return 'PASS: all 15 tools, image download, state retention, persistence, aliases, keyboard, mobile, missing route';
}
